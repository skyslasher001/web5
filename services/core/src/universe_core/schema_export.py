"""Export the OpenAPI schema and the event catalog for packages/shared-types (`pnpm gen:types`)."""

import json
import sys
from pathlib import Path

from universe_core.app import create_app
from universe_core.events import CATALOG
from universe_core.settings import CoreSettings

HEADER = "// GENERATED by `pnpm gen:types` from services/core (universe_core.events.CATALOG). Do not edit.\n"


def openapi() -> dict:
    app = create_app(CoreSettings(session_token="x" * 32))  # the schema doesn't need a running app
    return app.openapi()


def events_ts() -> str:
    entries = ",\n".join(
        f"  {json.dumps(name)}: {{ persisted: {str(spec.persisted).lower()}, "
        f"description: {json.dumps(spec.description)} }}"
        for name, spec in CATALOG.items()
    )
    return (
        HEADER
        + "export const EVENT_TYPES = {\n"
        + entries
        + ",\n} as const;\n\n"
        + "export type EventType = keyof typeof EVENT_TYPES;\n"
    )


def main() -> int:
    out = Path(sys.argv[1])
    # newline="\n": text mode would write CRLF on Windows and fail the drift check against LF files.
    (out / "openapi.json").write_text(
        json.dumps(openapi(), indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
    )
    (out / "src" / "events.ts").write_text(events_ts(), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
